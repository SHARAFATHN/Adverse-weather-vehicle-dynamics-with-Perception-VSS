SAMPLE_EVERY_N_SECONDS = 10

def extract_frames(video_path, every_n_sec=5):
    cap      = cv2.VideoCapture(video_path)
    fps_val  = cap.get(cv2.CAP_PROP_FPS)
    interval = max(1, int(fps_val * every_n_sec))
    frames   = []
    idx      = 0

    while True:
        ret, frame = cap.read()
        if not ret:
            break
        if idx % interval == 0:
            h, w = frame.shape[:2]
            if w > 1280:
                scale = 1280 / w
                frame = cv2.resize(frame,
                    (1280, int(h * scale)),
                    interpolation=cv2.INTER_AREA)
            pil_img   = Image.fromarray(
                cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
            timestamp = idx / fps_val
            frames.append({
                "timestamp"  : timestamp,
                "time_label" : f"{int(timestamp//60):02d}:{int(timestamp%60):02d}",
                "image"      : pil_img
            })
        idx += 1

    cap.release()
    return frames

