import json
from tqdm import tqdm

VLM_PROMPT = """Analyze this video frame carefully.
Return ONLY valid JSON — no markdown, no extra text:
{
  "scene": "one sentence describing the overall scene",
  "people": "number visible and what they are doing",
  "objects": ["main", "objects", "present"],
  "activity": "the main activity happening",
  "anomaly": "any safety issue or unusual event, or null"
}"""

def analyze_frame(pil_image):
    messages = [{
        "role": "user",
        "content": [
            {"type": "image", "image": pil_image},
            {"type": "text",  "text": VLM_PROMPT}
        ]
    }]
    text = vlm_processor.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    image_inputs, video_inputs = process_vision_info(messages)
    inputs = vlm_processor(
        text=[ text ],
        images=image_inputs,
        videos=video_inputs,
        padding=True,
        return_tensors="pt"
    ).to("cuda")

    with torch.no_grad():
        output_ids = vlm_model.generate(
            **inputs,
            max_new_tokens = 200,
            do_sample      = False,
        )

    new_tokens = output_ids[0][len(inputs.input_ids[0]):]
    raw = vlm_processor.decode(new_tokens, skip_special_tokens=True).strip()

    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        clean = raw.split("```json")[-1].split("```")[0].strip()
        try:
            return json.loads(clean)
        except:
            return {"scene": raw, "people": "", "objects": [],
                    "activity": "", "anomaly": None}

