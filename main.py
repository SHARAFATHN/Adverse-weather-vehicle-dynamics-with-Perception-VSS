def build_timeline(results):
    lines = []
    for r in results:
        flag = " [ANOMALY]" if r.get("anomaly") else ""
        line = (f"[{r['time_label']}]{flag}  "
                f"{r.get('scene','')}  |  "
                f"Activity: {r.get('activity','')}")
        lines.append(line)
    return "\n".join(lines)

def query_video(question, results):
    timeline = build_timeline(results)
    messages = [
        {"role": "system", "content": (
            "You are a precise video analyst. "
            "Answer questions using only the timestamped data. "
            "Always cite specific timestamps."
        )},
        {"role": "user", "content": (
            f"Video timeline ({len(results)} frames, "
            f"sampled every {SAMPLE_EVERY_N_SECONDS}s):\n\n"
            f"{timeline}\n\n"
            f"Question: {question}"
        )}
    ]
    text = llm_tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    inputs = llm_tokenizer([text], return_tensors="pt").to("cuda")

    with torch.no_grad():
        output = llm_model.generate(
            **inputs,
            max_new_tokens = 400,
            do_sample      = False,
        )

    new_tokens = output[0][inputs.input_ids.shape[1]:]
    return llm_tokenizer.decode(new_tokens, skip_special_tokens=True).strip()

